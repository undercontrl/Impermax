        const cardWidth = 450;
         
        document.addEventListener('DOMContentLoaded', () => {
            carrossel.scrollLeft = cardWidth;
        });
         
        btnDireita.onclick = () => {
            if (carrossel.scrollLeft + carrossel.offsetWidth >= carrossel.scrollWidth - 1) {
